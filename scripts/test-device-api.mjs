import assert from 'node:assert/strict';
import {createDeviceAPI,DEVICE_KEY} from '../src/assets/js/device-api.js';
const memory=new Map(),storage={getItem:key=>memory.get(key)??null,setItem:(key,value)=>memory.set(key,value)};
const validate=value=>{if(!value?.name)throw Error('Name required');return {...value};};
const api=createDeviceAPI(validate,()=>storage);
assert.equal((await api('/api/me')).mode,'device');
const {item}=await api('/api/creations','POST',{name:'Ovy',favorite:false});
assert.ok(item.id);assert.equal((await api('/api/creations')).items.length,1);
const reopened=createDeviceAPI(validate,()=>storage);
assert.equal((await reopened('/api/creations')).items[0].id,item.id);
await api('/api/creations/'+item.id,'PUT',{name:'Moon Ovy',favorite:true});
assert.equal((await reopened('/api/creations')).items[0].favorite,true);
const before=memory.get(DEVICE_KEY);
await assert.rejects(api('/api/creations','POST',{}));assert.equal(memory.get(DEVICE_KEY),before);
const blocked=createDeviceAPI(validate,()=>({...storage,setItem(){throw Error('quota');}}));
await assert.rejects(blocked('/api/creations','POST',{name:'Lost'}),{code:'storage'});
assert.equal(memory.get(DEVICE_KEY),before);
for(let i=1;i<200;i++)await api('/api/creations','POST',{name:'Ovy '+i});
await assert.rejects(api('/api/creations','POST',{name:'Overflow'}),{code:'limit'});
await api('/api/creations/'+item.id,'DELETE');
await assert.rejects(api('/api/creations/'+item.id,'PUT',{name:'Gone'}),{code:'not_found'});
memory.set(DEVICE_KEY,'corrupt');
await assert.rejects(api('/api/creations','POST',{name:'Overwrite'}),{code:'storage'});
assert.equal(memory.get(DEVICE_KEY),'corrupt');
console.log('PASS: device persistence, edits, deletion, limits, write failures and corrupt-data preservation.');
